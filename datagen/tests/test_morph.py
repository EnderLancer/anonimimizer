import pytest

from silver.fill.morph import inflect_full

CASES = [
    (("Коваль", "Іван", "Петрович", "masc"), "gent", ("Коваля", "Івана", "Петровича")),
    (("Коваль", "Ольга", "Петрівна", "femn"), "gent", ("Коваль", "Ольги", "Петрівни")),
    (("Шевченко", "Тарас", "Григорович", "masc"), "accs", ("Шевченка", "Тараса", "Григоровича")),
    (("Писаковська", "Ольга", "Іванівна", "femn"), "ablt", ("Писаковською", "Ольгою", "Іванівною")),
    (("Романишин", "Мар'яна", "Михайлівна", "femn"), "gent", ("Романишин", "Мар'яни", "Михайлівни")),
    (("Соя", "Дарина", "Андріївна", "femn"), "datv", ("Сої", "Дарині", "Андріївні")),
    (("Гнатюк", "Олександр", "Віталійович", "masc"), "gent", ("Гнатюка", "Олександра", "Віталійовича")),
    (("Мороз", "Юрій", "Олександрович", "masc"), "ablt", ("Морозом", "Юрієм", "Олександровичем")),
    (("Бойко-Петренко", "Наталія", "Олександрівна", "femn"), "accs", ("Бойко-Петренко", "Наталію", "Олександрівну")),
    (("Писаковський", "Олег", "Ігорович", "masc"), "gent", ("Писаковського", "Олега", "Ігоровича")),
]


@pytest.mark.parametrize("person,case,expected", CASES)
def test_inflection(person, case, expected):
    s, f, p, g = person
    assert inflect_full(s, f, p, g, case) == expected


def test_nominative_unchanged():
    assert inflect_full("Коваль", "Іван", "Петрович", "masc", "nomn") == ("Коваль", "Іван", "Петрович")
