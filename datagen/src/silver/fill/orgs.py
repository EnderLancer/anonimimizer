class OrgGenerator:
    def __init__(self, rng: random.Random):
        self.rng = rng

    def institution(self) -> str:
        r = self.rng
        kind = r.choices(["gu", "tck", "mou", "other", "unit"], [30, 25, 20, 10, 15])[0]
        if kind == "gu":
            body = r.choice(BODIES_GEN)
            place = r.choice([f"в {r.choice(REGIONS_LOC)} області", f"у {r.choice(CITIES_LOC)}"])
            return r.choice([f"Головного управління {body} {place}", f"Головне управління {body} {place}", f"Управління {body} {place}"])
        if kind == "tck":
            d = r.choice(DISTRICT_ADJ)
            form = r.choice([f"{d}ого районного територіального центру комплектування та соціальної підтримки",
                             f"{d}ого районного у місті Києві територіального центру комплектування та соціальної підтримки",
                             f"{r.choice(REGIONS_LOC).replace('ій', 'ого')} обласного територіального центру комплектування та соціальної підтримки",
                             f"{d}ий районний територіальний центр комплектування та соціальної підтримки", "ТЦК та СП",
                             f"{d}ого РТЦК та СП"])
            return form
        if kind == "mou":
            return r.choice(MOU_DEPTS)
        if kind == "other":
            return r.choice(OTHER)
        return self.unit_name()

    def unit_name(self) -> str:
        r = self.rng
        if r.random() < 0.55:
            return f"{r.choice(['Військова частина', 'Військова частина', 'військова частина', 'в/ч'])} {r.choice(['А', 'А', 'В', 'Т'])}{r.randint(1000, 9999)}"
        return f"{r.choice(UNIT_TYPES)} «{r.choice(UNIT_NAMES)}»"
