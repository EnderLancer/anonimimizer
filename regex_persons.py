"""Прогін «чисто regex»: без нейромережі й CRF. ОСОБА — лише морфологічні шаблони (по батькові, ініціали),
НОМЕР / ІНФОРМАЦІЯ / АДРЕСА — правила з predict_trf.py. Тест не використовується для підбору правил.
python run_regex_only.py cases.jsonl out.jsonl"""
import re

W = r"[А-ЯІЇЄҐ][а-яіїєґ'’ʼ]+(?:-[А-ЯІЇЄҐ][а-яіїєґ'’ʼ]+)?"
PATR = r"[А-ЯІЇЄҐ][а-яіїєґ'’ʼ]*(?:(?:ович|евич|євич|йович|ич)(?:а|у|і|ем|еві|ові)?|(?:івн|ївн|овн|евн|євн)(?:а|и|і|у|ою))"
INI = r"[А-ЯІЇЄҐ]\.\s?(?:[А-ЯІЇЄҐ]\.)?"
PERSON_RES = [
    re.compile(rf"(?<![\w'’-])(?:{W}\s+){{1,2}}{PATR}(?![\w'’-])"),           # Прізвище Ім'я По-батькові / Ім'я По-батькові
    re.compile(rf"(?<![\w'’-]){PATR}\s+{W}(?![\w'’-])"),                       # По-батькові Прізвище (рідко)
    re.compile(rf"(?<![\w'’-]){W}\s+[А-ЯІЇЄҐ]\.\s?[А-ЯІЇЄҐ]\.(?![\w])"),       # Прізвище І. П.
    re.compile(rf"(?<![\w'’-])[А-ЯІЇЄҐ]\.\s?[А-ЯІЇЄҐ]\.\s?{W}(?![\w'’-])"),   # І. П. Прізвище
    re.compile(rf"(?<![\w'’-]){W}\s+[А-ЯІЇЄҐ]\.(?![\w.])"),                     # Прізвище І.
]
ROLE = {"позивач", "відповідач", "заявник", "потерпілий", "обвинувачений", "скаржник", "боржник", "стягувач", "особа", "громадянин", "громадянка",
        "пан", "пані", "суддя", "прокурор", "адвокат", "представник", "свідок", "третя", "треті", "ухвала", "рішення", "справа", "згідно", "відповідно",
        "позивачка", "відповідачка", "заявниця", "позивача", "відповідача", "заявника", "позивачу", "відповідачу", "заявнику", "позивачем", "відповідачем",
        "заявником", "позивачки", "відповідачки", "заявниці", "позивачці", "відповідачці", "позивачкою", "відповідачкою", "представника",
        "представником", "представнику", "громадянина", "громадянину", "громадянином", "громадянки", "громадянці", "громадянкою", "суду", "суд"}

def persons(text):
    spans = []
    for R in PERSON_RES:
        for m in R.finditer(text):
            s, e = m.start(), m.end()
            # зняти службові слова з початку
            while True:
                mm = re.match(r"([^\W\d_][\w'’ʼ-]*)\s+", text[s:e])
                if mm and mm.group(1).lower() in ROLE and len(text[s:e].split()) > 1:
                    s += mm.end()
                else:
                    break
            if text[s:e].split()[0].lower() in ROLE:
                continue
            spans.append((s, e, "x"))
    spans.sort(key=lambda x: -(x[1] - x[0]))
    kept = []
    for sp in spans:
        if not any(sp[0] < k[1] and k[0] < sp[1] for k in kept):
            kept.append(sp)
    return kept

